"""Object storage for document files.

Files never go into PostgreSQL. `local` writes under a directory (development);
`s3` talks to Amazon S3 or any S3-compatible service.

Keys are generated by the application, never taken from user input, and both
adapters still reject anything that is not a plain relative path.
"""

import re
import shutil
import uuid
from collections.abc import Iterator
from functools import lru_cache
from pathlib import Path
from typing import BinaryIO, Protocol

from app.core.config import Settings, get_settings

CHUNK_SIZE = 64 * 1024
_KEY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._\-]*(/[A-Za-z0-9][A-Za-z0-9._\-]*)*$")


class StorageError(RuntimeError):
    pass


class StorageKeyError(StorageError):
    """The key is not a safe relative path."""


class StoredFileNotFoundError(StorageError):
    pass


def validate_key(key: str) -> str:
    if len(key) > 512 or ".." in key or not _KEY_PATTERN.match(key):
        raise StorageKeyError(f"Unsafe storage key: {key!r}")
    return key


def document_key(
    organization_id: uuid.UUID, document_id: uuid.UUID, version_id: uuid.UUID, extension: str
) -> str:
    """Where one version of one document lives. Grouped by organization."""
    return validate_key(f"organizations/{organization_id}/documents/{document_id}/{version_id}{extension}")


class Storage(Protocol):
    def save(self, key: str, data: BinaryIO, content_type: str) -> None: ...

    def open(self, key: str) -> Iterator[bytes]:
        """Yield the file in chunks. Raises StoredFileNotFoundError."""

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None:
        """Remove the file. Missing files are ignored."""


class LocalStorage:
    def __init__(self, directory: str) -> None:
        self._root = Path(directory).resolve()

    def _path(self, key: str) -> Path:
        path = (self._root / validate_key(key)).resolve()
        if not path.is_relative_to(self._root):
            raise StorageKeyError(f"Unsafe storage key: {key!r}")
        return path

    def save(self, key: str, data: BinaryIO, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temporary name first so a failed upload never leaves a partial file.
        temporary = path.with_name(f".{path.name}.{uuid.uuid4().hex}.part")
        try:
            with temporary.open("wb") as target:
                shutil.copyfileobj(data, target, CHUNK_SIZE)
            temporary.replace(path)
        except BaseException:
            temporary.unlink(missing_ok=True)
            raise

    def open(self, key: str) -> Iterator[bytes]:
        path = self._path(key)
        if not path.is_file():
            raise StoredFileNotFoundError(key)

        def chunks() -> Iterator[bytes]:
            with path.open("rb") as source:
                while chunk := source.read(CHUNK_SIZE):
                    yield chunk

        return chunks()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    def __init__(self, settings: Settings) -> None:
        if not settings.s3_bucket:
            raise StorageError("S3_BUCKET is required when STORAGE_BACKEND=s3")
        import boto3

        self._bucket = settings.s3_bucket
        # Ask AWS to encrypt at rest. S3-compatible services differ in what they
        # accept here, so with a custom endpoint encryption is left to the bucket's own policy.
        self._extra_args = {} if settings.s3_endpoint_url else {"ServerSideEncryption": "AES256"}
        self._client = boto3.client(
            "s3",
            region_name=settings.s3_region,
            endpoint_url=settings.s3_endpoint_url,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key,
        )

    def save(self, key: str, data: BinaryIO, content_type: str) -> None:
        self._client.upload_fileobj(
            data,
            self._bucket,
            validate_key(key),
            ExtraArgs={"ContentType": content_type, **self._extra_args},
        )

    def open(self, key: str) -> Iterator[bytes]:
        from botocore.exceptions import ClientError

        try:
            response = self._client.get_object(Bucket=self._bucket, Key=validate_key(key))
        except ClientError as error:
            if error.response.get("Error", {}).get("Code") in ("NoSuchKey", "404"):
                raise StoredFileNotFoundError(key) from error
            raise
        return response["Body"].iter_chunks(CHUNK_SIZE)

    def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        try:
            self._client.head_object(Bucket=self._bucket, Key=validate_key(key))
        except ClientError as error:
            if error.response.get("Error", {}).get("Code") in ("NoSuchKey", "404", "NotFound"):
                return False
            raise
        return True

    def delete(self, key: str) -> None:
        self._client.delete_object(Bucket=self._bucket, Key=validate_key(key))


@lru_cache
def get_storage() -> Storage:
    settings = get_settings()
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(settings.storage_local_dir)
